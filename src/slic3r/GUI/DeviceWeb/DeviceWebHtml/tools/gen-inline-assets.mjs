// Inlines the small SVG overlays that are composited *inside* an <svg> as data
// URIs, matching what Vite does for the React build.
//
// These are not plain <img> decorations: they are <image> children of the spool
// and nozzle SVGs, layered over the colour donut with fill-opacity. Referencing
// them as external files rasterises measurably differently from an inlined data
// URI (tools/compare-pages.mjs showed a ~0.17% pixel delta concentrated on the
// spool tag), so the front-end inlines them the same way the React build does.
//
// Only overlays go here. Ordinary standalone icons stay as files in web/assets/.
//
// Run after changing any listed asset:
//   node src/slic3r/GUI/DeviceWeb/DeviceWebHtml/tools/gen-inline-assets.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const assetsDir = resolve(here, '../web/assets');
const outFile = resolve(here, '../web/js/inline-assets.js');

const INLINED = [
  ['SPOOL_FILAMENT_TAG', 'spool_filament_tag_figma.svg'],
  ['SPOOL_UNKNOWN', 'spool_unknown_figma.svg'],
  ['PREFEED_UNKNOWN', 'prefeed_unknown.svg'],
  ['HOTEND_LOST_BADGE', 'hotend_lost_badge.svg'],
];

// Mirrors Vite's svg data-URI encoding: keep the payload readable and only
// escape what actually breaks an unquoted attribute value.
function encode(svg) {
  const collapsed = svg.replace(/\s+/g, ' ').trim();
  return 'data:image/svg+xml,' + collapsed
    .replace(/%/g, '%25')
    .replace(/#/g, '%23')
    .replace(/</g, '%3c')
    .replace(/>/g, '%3e')
    .replace(/"/g, "'")
    .replace(/\s/g, '%20');
}

const entries = INLINED.map(([name, file]) => {
  const svg = readFileSync(join(assetsDir, file), 'utf8');
  return `  ${name}: ${JSON.stringify(encode(svg))},`;
});

const body = `// Generated by tools/gen-inline-assets.mjs. Do not edit.
//
// SVG overlays composited inside other SVGs, inlined as data URIs so they
// rasterise identically to the React build (see the generator for why).
(function (global) {
  'use strict';
  var BBL = global.BBL || (global.BBL = {});
  BBL.inlineAssets = {
${entries.join('\n')}
  };
})(window);
`;

writeFileSync(outFile, body, 'utf8');
console.log(`inline-assets.js written: ${INLINED.length} assets, ${(body.length / 1024).toFixed(1)} KB`);

// Extracts the design tokens and base reset from the React build output into
// web/css/tokens.css.
//
// ams-filament-hotend.css resolves every colour through --ams-* / --color-fm-*
// custom properties, but those are declared in device_page/src/styles.css using
// Tailwind 4's `@theme { }`, which no browser understands - Tailwind compiles it
// into plain `:root { --x: ... }`. So the compiled stylesheet is the only usable
// source, exactly as it is for the locales.
//
// Rules kept:
//   1. every rule that declares at least one custom property (tokens, plus the
//      [data-theme=light] / [data-theme=dark] overrides), custom properties only
//   2. the `@layer base` preflight, which ams-filament-hotend.css assumes
//      (border-box sizing, margin reset, inherited font)
//
// Run after changing styles.css or rebuilding device_page:
//   node src/slic3r/GUI/DeviceWeb/DeviceWebHtml/tools/gen-tokens.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const srcCss = resolve(here, '../../device_page/dist/assets/index.css');
const outCss = resolve(here, '../web/css/tokens.css');

if (!existsSync(srcCss)) {
  console.error(`missing ${srcCss}\nBuild device_page first (pnpm build).`);
  process.exit(1);
}

// Comments must go first: a leading `/*! tailwindcss */` would otherwise become
// part of the next rule's selector, which both breaks that rule and hides the
// `@layer` prefix from the at-rule check below.
const css = readFileSync(srcCss, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

// Split the top level into { selector, body } pairs. Depth tracking is enough
// here: the compiled sheet has no strings or comments containing braces.
function topLevelRules(text) {
  const rules = [];
  let depth = 0;
  let start = 0;
  let selectorStart = 0;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === '{') {
      if (depth === 0) {
        start = i;
        rules.push({ selector: text.slice(selectorStart, i).trim(), bodyStart: i + 1 });
      }
      depth++;
    } else if (ch === '}') {
      depth--;
      if (depth === 0) {
        const rule = rules[rules.length - 1];
        rule.body = text.slice(rule.bodyStart, i);
        rule.raw = text.slice(selectorStart, i + 1);
        selectorStart = i + 1;
      }
    }
  }
  return rules.filter((r) => r.body !== undefined);
}

const chunks = [];
let tokenRuleCount = 0;
let tokenCount = 0;

// Tailwind emits `@theme` into `@layer theme { :root { --color-*: ... } }`, so
// the token rules are one level down. Recurse into @layer and flatten: layered
// rules only ever lose to unlayered ones, and the compiled sheet already lists
// the layers before the unlayered rules, so file order reproduces the cascade.
function collectTokenRules(text) {
  for (const rule of topLevelRules(text)) {
    if (/^@layer\b/.test(rule.selector)) {
      collectTokenRules(rule.body);
      continue;
    }
    if (rule.selector.startsWith('@')) continue;
    const declarations = rule.body
      .split(';')
      .map((d) => d.trim())
      .filter((d) => d.startsWith('--'));
    if (!declarations.length) continue;
    tokenRuleCount++;
    tokenCount += declarations.length;
    chunks.push(`${rule.selector} {\n  ${declarations.join(';\n  ')};\n}`);
  }
}
collectTokenRules(css);

// Preflight, kept inside its layer so page rules still win over it.
const baseLayer = topLevelRules(css).find((r) => /^@layer\s+base$/.test(r.selector));
if (baseLayer) chunks.push(`@layer base {${baseLayer.body}}`);

const header = `/* Generated by tools/gen-tokens.mjs from device_page/dist/assets/index.css.
   Do not edit. Re-run the generator after changing styles.css. */\n\n`;

writeFileSync(outCss, header + chunks.join('\n\n') + '\n', 'utf8');

const size = (header.length + chunks.join('\n\n').length) / 1024;
console.log(`tokens.css written: ${tokenRuleCount} rules, ${tokenCount} custom properties, `
  + `preflight ${baseLayer ? 'included' : 'NOT FOUND'}, ${size.toFixed(1)} KB`);

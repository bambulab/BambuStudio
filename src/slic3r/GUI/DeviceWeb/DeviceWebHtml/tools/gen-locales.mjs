// Converts device_page/locales/*.json into classic scripts under web/locales/.
//
// Needed because fetch()/XHR against file:// is blocked in both WKWebView and
// WebView2, so the HTML front-end cannot read the JSON at runtime. A <script>
// tag can be injected from a file:// document, hence the thin JS wrapper.
//
// Run after changing translations:
//   node src/slic3r/GUI/DeviceWeb/DeviceWebHtml/tools/gen-locales.mjs
//
// This is a source-generation step, not a build step: the output is committed so
// CMake stays a plain directory copy with no Node dependency.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = resolve(here, '../../device_page/locales');
const outDir = resolve(here, '../web/locales');

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const files = readdirSync(srcDir).filter((name) => name.endsWith('.json'));
let total = 0;

for (const file of files) {
  const code = file.replace(/\.json$/, '');
  const json = JSON.parse(readFileSync(join(srcDir, file), 'utf8'));
  const body = `// Generated by tools/gen-locales.mjs from device_page/locales/${file}. Do not edit.
window.BBL.i18n.register(${JSON.stringify(code)}, ${JSON.stringify(json)});
`;
  const outPath = join(outDir, `${code}.js`);
  writeFileSync(outPath, body, 'utf8');
  total += Buffer.byteLength(body);
}

console.log(`generated ${files.length} locale scripts (${(total / 1024).toFixed(1)} KB) -> ${outDir}`);

import { expect, test } from '@playwright/test';

test('RFID assignment is explicit, cancelable, persistent in the bridge and removable', async ({ page }) => {
  await page.goto('/#/filament_manager?lang=en');
  const row = page.getByTestId('filament-row-sp-1');
  await expect(row).toBeVisible();
  await row.getByTestId('filament-row-detail').click();
  const editor = page.getByTestId('rfid-override');
  await expect(editor).toBeVisible();
  await editor.getByRole('button', { name: 'Assign actual filament...' }).click();
  await expect(editor.getByRole('button', { name: 'Save assignment' })).toBeDisabled();
  await editor.getByRole('combobox').selectOption('Third-party PLA @Test printer 0.4');
  await editor.locator('input[type=color]').fill('#ff6600');
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(editor).toContainText('No override');
  await editor.getByRole('button', { name: 'Assign actual filament...' }).click();
  await expect(editor.getByRole('combobox')).toHaveValue('');
  await editor.getByRole('combobox').selectOption('Calibrated PLA @Test printer 0.4');
  await editor.locator('input[type=color]').fill('#ff6600');
  await editor.getByRole('button', { name: 'Save assignment' }).click();
  await expect(editor).toContainText('User override');
  await expect(editor).toContainText('Calibrated PLA @Test printer 0.4');
  await page.getByTestId('detail-dialog-close').click();
  await expect(row).toContainText('User override');
  await expect(row.getByTestId('filament-row-name')).toHaveText('CC3D PLA Silk');
  await expect(row).toContainText('Original: Bambu Lab Basic');
  await expect(row).toContainText('#FF6600');
  await page.getByPlaceholder('Search Filament').fill('CC3D');
  await expect(row).toBeVisible();
  await page.getByPlaceholder('Search Filament').fill('Bambu');
  await expect(row).toHaveCount(0);
  await page.getByPlaceholder('Search Filament').fill('');
  await row.getByTestId('filament-row-detail').click();
  await expect(editor).toContainText('Calibrated PLA @Test printer 0.4');
  await editor.scrollIntoViewIfNeeded();
  await page.screenshot({ path: '/tmp/bambu-rfid-assignment-preview.png' });
  await editor.getByRole('button', { name: 'Remove override' }).click();
  await expect(editor).toContainText('No override');
  await page.getByTestId('detail-dialog-close').click();
  await expect(row.getByTestId('filament-row-name')).toHaveText('Bambu Lab Basic');
  await expect(row).not.toContainText('User override');
});

// Real top-view silhouette of an instance (non-convex, holes kept), in the same frame as the
// convex hull returned by ModelInstance::get_arrange_polygon() (instance transformation without
// the XY offset).
static ExPolygons instance_footprint(const ModelInstance *instance)
{
    const ModelObject *obj = instance->get_object();
    Geometry::Transformation trafo = instance->get_transformation();
    trafo.set_offset(Vec3d(0, 0, instance->get_offset(Z)));
    Polygons projections;
    for (const ModelVolume *v : obj->volumes)
        if (v->is_model_part())
            append(projections, project_mesh(v->mesh().its, trafo.get_matrix() * v->get_matrix(), []() {}));
    ExPolygons footprint;
    for (const ExPolygon &ex : union_ex(projections))
        append(footprint, ex.simplify(scale_(0.05)));
    // drop slivers
    footprint.erase(std::remove_if(footprint.begin(), footprint.end(), [](const ExPolygon &ex) { return ex.area() < scale_(0.1) * scale_(0.1); }),
                    footprint.end());
    return footprint;
}

// Estimate of the room supports need, used until update_support_areas() replaces it by the supports
// the slicer generates (or if generating them fails): every area which holds up supports, grown by
// how far supports may reach sideways from it. Tree branches below an overhang above the model
// move outwards around the model until they reach the bed, and grow there up to
// TreeSupport::MAX_BRANCH_RADIUS_FIRST_LAYER (12 mm). Normal supports grow straight down; 6 mm is the
// margin the libnest2d based arrangement has always reserved for them.
static constexpr double TREE_SUPPORT_REACH   = 18.;
static constexpr double NORMAL_SUPPORT_REACH = 6.;
// Extra room kept around supports generated by the slicer.
static constexpr double SLICED_SUPPORT_MARGIN = 1.;

// Top view of everything which will hold up supports: faces overhanging more than the support
// threshold angle above the first layer (automatic supports only), support enforcer volumes and
// painted enforcer facets. A raft covers the whole footprint. Same frame as instance_footprint().
// Empty if the instance does not get any support, even when supports are enabled.
static ExPolygons instance_support_seeds(const ModelInstance *instance, const DynamicPrintConfig &config, bool auto_support,
                                         const ExPolygons &footprint)
{
    ModelObject *obj = instance->get_object();
    auto raft_ptr = obj->get_config_value<ConfigOptionInt>(config, "raft_layers");
    if (raft_ptr && raft_ptr->value > 0) return footprint;

    Geometry::Transformation trafo = instance->get_transformation();
    trafo.set_offset(Vec3d(0, 0, instance->get_offset(Z)));
    const Transform3d inst = trafo.get_matrix();

    double zmin = std::numeric_limits<double>::max();
    for (const ModelVolume *v : obj->volumes) {
        if (!v->is_model_part()) continue;
        const Transform3d m = inst * v->get_matrix();
        for (const stl_vertex &p : v->mesh().its.vertices) zmin = std::min(zmin, (m * p.cast<double>()).z());
    }

    Polygons seeds;
    auto add_triangle = [&seeds](const Vec3d &a, const Vec3d &b, const Vec3d &c) {
        Polygon t({Point::new_scale(a.x(), a.y()), Point::new_scale(b.x(), b.y()), Point::new_scale(c.x(), c.y())});
        if (std::abs(t.area()) < 1.) return;
        if (t.is_clockwise()) t.reverse();
        seeds.emplace_back(std::move(t));
    };

    double cos_thr = 2.;
    if (auto_support) {
        auto thr_ptr = obj->get_config_value<ConfigOptionInt>(config, "support_threshold_angle");
        int  thr     = thr_ptr ? thr_ptr->value : 30;
        if (thr <= 0) thr = 30;
        cos_thr = std::cos(double(thr) * M_PI / 180.);
    }
    for (const ModelVolume *v : obj->volumes) {
        const Transform3d m = inst * v->get_matrix();
        if (v->is_support_enforcer()) {
            append(seeds, project_mesh(v->mesh().its, m, []() {}));
            continue;
        }
        if (!v->is_model_part()) continue;
        if (!v->supported_facets.empty()) {
            const indexed_triangle_set painted = v->supported_facets.get_facets(*v, EnforcerBlockerType::ENFORCER);
            for (const stl_triangle_vertex_indices &f : painted.indices)
                add_triangle(m * painted.vertices[f[0]].cast<double>(), m * painted.vertices[f[1]].cast<double>(),
                             m * painted.vertices[f[2]].cast<double>());
        }
        if (!auto_support) continue;
        const indexed_triangle_set &its = v->mesh().its;
        for (const stl_triangle_vertex_indices &f : its.indices) {
            const Vec3d a = m * its.vertices[f[0]].cast<double>();
            const Vec3d b = m * its.vertices[f[1]].cast<double>();
            const Vec3d c = m * its.vertices[f[2]].cast<double>();
            if (std::max({a.z(), b.z(), c.z()}) <= zmin + 0.2) continue; // lies on the bed
            const Vec3d  n   = (b - a).cross(c - a);
            const double len = n.norm();
            if (len > 0. && -n.z() / len > cos_thr) add_triangle(a, b, c);
        }
    }
    if (seeds.empty()) return {};
    // close the gaps between neighbouring triangles, drop tiny overhangs which get no support
    ExPolygons out = offset_ex(union_(seeds), float(scale_(0.05)));
    out.erase(std::remove_if(out.begin(), out.end(), [](const ExPolygon &ex) { return ex.area() < scale_(0.5) * scale_(1.); }), out.end());
    return out;
}

// Supports of an instance as the slicer generates them: the object is sliced alone, in the middle of
// the bed, with the same orientation and scaling, and only its supports are generated. Returns their
// top view grown by SLICED_SUPPORT_MARGIN, in the frame of instance_footprint(). Results are cached
// by geometry, orientation and configuration, so repeated arrangements and identical instances are
// only sliced once.
static bool slice_instance_supports(const ModelInstance *instance, const DynamicPrintConfig &config, ExPolygons &out)
{
    const ModelObject *src = instance->get_object();
    // cache key
    auto config_hash = [](const ConfigBase &cfg) {
        size_t seed = 0;
        for (const std::string &k : cfg.keys())
            if (const ConfigOption *opt = cfg.option(k))
                seed ^= std::hash<std::string>{}(k) + opt->hash() + 0x9e3779b97f4a7c15ULL + (seed << 6) + (seed >> 2);
        return std::to_string(seed);
    };
    auto serialize = [&config_hash](const ModelConfig &cfg) { return config_hash(cfg.get()); };
    // Identified by content, not by object ID: copies of an object get the same supports.
    std::string key = serialize(src->config) + "/";
    for (double h : src->layer_height_profile.get()) key += std::to_string(std::llround(h * 1e4)) + ",";
    for (const ModelVolume *v : src->volumes) {
        const indexed_triangle_set &its = v->mesh().its;
        const size_t mesh_hash = std::hash<std::string_view>{}(std::string_view(reinterpret_cast<const char *>(its.vertices.data()),
                                                                                its.vertices.size() * sizeof(stl_vertex))) ^
                                 (std::hash<std::string_view>{}(std::string_view(reinterpret_cast<const char *>(its.indices.data()),
                                                                                 its.indices.size() * sizeof(stl_triangle_vertex_indices))) << 1);
        key += "|" + std::to_string(mesh_hash) + ":" + std::to_string(int(v->type())) + ":" + serialize(v->config) + ":" +
               (v->supported_facets.empty() ? std::string() : std::to_string(v->id().id) + "/" + std::to_string(v->supported_facets.timestamp()));
        const Transform3d &m = v->get_matrix();
        for (int i = 0; i < 12; ++i) key += "," + std::to_string(std::llround(m.data()[i] * 1e4));
    }
    const Transform3d inst = instance->get_transformation().get_matrix();
    for (int r = 0; r < 3; ++r)
        for (int c = 0; c < 3; ++c) key += "," + std::to_string(std::llround(inst(r, c) * 1e4));
    key += "#" + config_hash(config);

    static std::mutex                                    cache_mutex;
    static std::list<std::pair<std::string, ExPolygons>> cache; // most recently used first
    {
        std::lock_guard<std::mutex> lock(cache_mutex);
        for (auto it = cache.begin(); it != cache.end(); ++it)
            if (it->first == key) {
                cache.splice(cache.begin(), cache, it);
                out = it->second;
                return true;
            }
    }

    try {
        Model model;
        ModelObject *obj = model.add_object(*src);
        while (obj->instances.size() > 1) obj->delete_instance(obj->instances.size() - 1);
        ModelInstance *mi = obj->instances.front();
        mi->set_transformation(instance->get_transformation());
        mi->printable = true;
        const BoundingBox bed = BoundingBox(get_bed_shape(config));
        const Vec2d center = unscaled(bed.center());
        mi->set_offset(X, center.x());
        mi->set_offset(Y, center.y());
        obj->ensure_on_bed();
        const Vec3d offset = mi->get_offset();

        auto t0 = std::chrono::steady_clock::now();
        Print print;
        print.set_status_silent();
        print.apply(model, config);
        if (print.objects().empty()) return false;
        auto t1 = std::chrono::steady_clock::now();
        print.process_supports_only();
        BOOST_LOG_TRIVIAL(info) << "arrange: supports of " << src->name << " generated, apply "
                                << std::chrono::duration<double>(t1 - t0).count() << "s, slicing and supports "
                                << std::chrono::duration<double>(std::chrono::steady_clock::now() - t1).count() << "s";

        const PrintObject *po = print.objects().front();
        // Top view of all support layers, with a little extra room: the nester also rotates objects,
        // which slightly changes their supports.
        std::vector<Polygons> layers(po->support_layers().size());
        tbb::parallel_for(tbb::blocked_range<size_t>(0, layers.size()), [&](const tbb::blocked_range<size_t> &range) {
            for (size_t i = range.begin(); i < range.end(); ++i) {
                const SupportLayer *layer = po->support_layers()[i];
                Polygons polys = layer->support_fills.polygons_covered_by_width(float(scale_(0.01)));
                append(polys, to_polygons(layer->support_islands));
                layers[i] = union_(polys);
            }
        });
        Polygons all;
        for (Polygons &l : layers) append(all, std::move(l));
        ExPolygons supports;
        for (ExPolygon &e : offset_ex(union_ex(all), float(scale_(SLICED_SUPPORT_MARGIN)), ClipperLib::jtRound, scale_(0.1)))
            append(supports, e.simplify(scale_(0.05)));
        // print object coordinates -> instance frame without the XY offset
        const Point shift = po->instances().front().shift - Point::new_scale(offset.x(), offset.y());
        for (ExPolygon &e : supports) e.translate(shift);
        out = std::move(supports);
    } catch (const std::exception &e) {
        BOOST_LOG_TRIVIAL(warning) << "arrange: generating the supports of " << src->name << " failed: " << e.what();
        return false;
    }

    std::lock_guard<std::mutex> lock(cache_mutex);
    cache.emplace_front(key, out);
    if (cache.size() > 64) cache.pop_back();
    return true;
}

void update_support_areas(ArrangePolygons &items, const DynamicPrintConfig &config, std::function<bool()> stop,
                          std::function<void(const std::string &name)> progress)
{
    for (ArrangePolygon &ap : items) {
        if (stop && stop()) return;
        if (!ap.slice_supports) continue;
        if (progress) progress(ap.name);
        ExPolygons supports;
        if (!ap.slice_supports(config, supports)) continue; // keep the estimate
        ap.support_area = diff_ex(supports, ap.footprint);
        if (supports.empty()) {
            ap.brim_width       = 0.;
            ap.has_tree_support = false;
        }
    }
}

arrangement::ArrangePolygons get_arrange_polys(const Model &model, ModelInstancePtrs &instances)
{
    size_t count = 0;
    for (auto obj : model.objects) count += obj->instances.size();

    ArrangePolygons input;
    input.reserve(count);
    instances.clear(); instances.reserve(count);
    ArrangePolygon ap;
    for (ModelObject *mo : model.objects)
        for (ModelInstance *minst : mo->instances) {
            minst->get_arrange_polygon(&ap);
            input.emplace_back(ap);
            instances.emplace_back(minst);
        }

    return input;
}

bool apply_arrange_polys(ArrangePolygons &input, ModelInstancePtrs &instances, VirtualBedFn vfn)
{
    bool ret = true;

    for(size_t i = 0; i < input.size(); ++i) {
        if (input[i].bed_idx != 0) { ret = false; if (vfn) vfn(input[i]); }
        if (input[i].bed_idx >= 0)
            instances[i]->apply_arrange_result(input[i].translation.cast<double>(),
                                               input[i].rotation);
    }

    return ret;
}

Slic3r::arrangement::ArrangePolygon get_arrange_poly(const Model &model)
{
    ArrangePolygon ap;
    Points &apts = ap.poly.contour.points;
    for (const ModelObject *mo : model.objects)
        for (const ModelInstance *minst : mo->instances) {
            ArrangePolygon obj_ap;
            minst->get_arrange_polygon(&obj_ap);
            ap.poly.contour.rotate(obj_ap.rotation);
            ap.poly.contour.translate(obj_ap.translation.x(), obj_ap.translation.y());
            const Points &pts = obj_ap.poly.contour.points;
            std::copy(pts.begin(), pts.end(), std::back_inserter(apts));
        }

    apts = std::move(Geometry::convex_hull(apts).points);
    return ap;
}

void duplicate(Model &model, Slic3r::arrangement::ArrangePolygons &copies, VirtualBedFn vfn)
{
    for (ModelObject *o : model.objects) {
        // make a copy of the pointers in order to avoid recursion when appending their copies
        ModelInstancePtrs instances = o->instances;
        o->instances.clear();
        for (const ModelInstance *i : instances) {
            for (arrangement::ArrangePolygon &ap : copies) {
                if (ap.bed_idx != 0) vfn(ap);
                ModelInstance *instance = o->add_instance(*i);
                Vec2d pos = unscale(ap.translation);
                instance->set_offset(instance->get_offset() + to_3d(pos, 0.));
            }
        }
        o->invalidate_bounding_box();
    }
}

void duplicate_objects(Model &model, size_t copies_num)
{
    for (ModelObject *o : model.objects) {
        // make a copy of the pointers in order to avoid recursion when appending their copies
        ModelInstancePtrs instances = o->instances;
        for (const ModelInstance *i : instances)
            for (size_t k = 2; k <= copies_num; ++ k)
                o->add_instance(*i);
    }
}

// Set up arrange polygon for a ModelInstance and Wipe tower
template<class T>
arrangement::ArrangePolygon get_arrange_poly(T obj, const Slic3r::DynamicPrintConfig& config)
{
    ArrangePolygon ap = obj.get_arrange_polygon(config);
    //BBS: always set bed_idx to 0 to use original transforms with no bed_idx
    //if this object is not arranged, it can keep the original transforms
    //ap.bed_idx        = ap.translation.x() / bed_stride_x(plater);
    ap.bed_idx = 0;
    ap.setter = [obj](const ArrangePolygon& p) {
        if (p.is_arranged()) {
            Vec2d t = p.translation.cast<double>();
            //BBS: change to sudoku-style computation, do it in partplate list
            //t.x() += p.bed_idx * bed_stride(plater);
            //t.x() += col * bed_stride_x(plater);
            //t.y() -= row * bed_stride_y(plater);
            T{ obj }.apply_arrange_result(t, p.rotation, p.itemid);
        }
    };

    return ap;
}

template<>
arrangement::ArrangePolygon get_arrange_poly(ModelInstance* inst, const Slic3r::DynamicPrintConfig& config)
{
    return get_arrange_poly(PtrWrapper{ inst },config);
}

ArrangePolygon get_instance_arrange_poly(ModelInstance* instance, const Slic3r::DynamicPrintConfig& config)
{
    ArrangePolygon ap = get_arrange_poly(PtrWrapper{ instance }, config);
    int            first_extruder_id = ap.extrude_id_filament_types.begin()->first - 1;
    //BBS: add temperature information
    if (config.has("curr_bed_type")) {
        ap.bed_temp = 0;
        ap.first_bed_temp = 0;
        BedType curr_bed_type = config.opt_enum<BedType>("curr_bed_type");

        const ConfigOptionInts* bed_opt = config.option<ConfigOptionInts>(get_bed_temp_key(curr_bed_type));
        if (bed_opt != nullptr) ap.bed_temp = bed_opt->get_at(first_extruder_id);

        const ConfigOptionInts* bed_opt_1st_layer = config.option<ConfigOptionInts>(get_bed_temp_1st_layer_key(curr_bed_type));
        if (bed_opt_1st_layer != nullptr)
            ap.first_bed_temp = bed_opt_1st_layer->get_at(first_extruder_id);
    }

    if (config.has("nozzle_temperature")) //get the print temperature
        ap.print_temp = config.opt_int_nullable("nozzle_temperature", first_extruder_id);
    if (config.has("nozzle_temperature_initial_layer")) //get the nozzle_temperature_initial_layer
        ap.first_print_temp = config.opt_int_nullable("nozzle_temperature_initial_layer", first_extruder_id);

    if (config.has("temperature_vitrification")) {
        ap.vitrify_temp = config.opt_int("temperature_vitrification", first_extruder_id);
    }

    // get filament temp types
    auto* filament_types_opt = dynamic_cast<const ConfigOptionStrings*>(config.option("filament_type"));
    if (filament_types_opt) {
        std::set<int> filament_temp_types;
        for (auto id : ap.extrude_id_filament_types) {
            std::string type_str = filament_types_opt->get_at(id.first-1);
            int temp_type = Print::get_filament_temp_type(type_str);
            filament_temp_types.insert(temp_type);
        }
        ap.filament_temp_type = Print::get_compatible_filament_type(filament_temp_types);
    }

    // get brim width
    auto obj = instance->get_object();

    ap.brim_width = 0.0;
    // For by-layer printing, need to shrink bed a little, so the support won't go outside bed.
    // We set it to 5mm because that's how much a normal support will grow by default.
    // normal support 5mm, other support 22mm, no support 0mm
    auto supp_type_ptr = obj->get_config_value<ConfigOptionBool>(config, "enable_support");
    auto support_type_ptr = obj->get_config_value<ConfigOptionEnum<SupportType>>(config, "support_type");
    auto support_type = support_type_ptr->value;
    auto enable_support = supp_type_ptr->getBool();
    auto raft_first_layer_expansion_ptr = obj->get_config_value<ConfigOptionFloat>(config, "raft_first_layer_expansion");
    float raft_expansion                = raft_first_layer_expansion_ptr ? raft_first_layer_expansion_ptr->getFloat() : 0.0;
    ap.footprint = instance_footprint(instance);

    // Supports enabled but nothing to support: no room needs to be reserved for them.
    ExPolygons support_seeds;
    if (enable_support) {
        support_seeds = instance_support_seeds(instance, config, is_auto(support_type), ap.footprint);
        enable_support = !support_seeds.empty();
    }

    if (enable_support && (support_type == stNormalAuto || support_type == stNormal))
        ap.brim_width = 6.0;
    else if (enable_support) {
        ap.brim_width = std::max(24.0f, raft_expansion); // 2*MAX_BRANCH_RADIUS_FIRST_LAYER
        ap.has_tree_support = true;
    }
    // Room the supports may take around the object, used by the raster nester instead of a margin
    // around the whole object.
    if (enable_support) {
        const double reach = std::max(is_tree(support_type) ? TREE_SUPPORT_REACH : NORMAL_SUPPORT_REACH, double(raft_expansion));
        ap.support_area    = diff_ex(offset_ex(support_seeds, float(scale_(reach)), ClipperLib::jtRound, scale_(0.1)), ap.footprint);
        ap.slice_supports  = [instance](const DynamicPrintConfig &cfg, ExPolygons &supports) {
            return slice_instance_supports(instance, cfg, supports);
        };
    }

    auto size = obj->instance_convex_hull_bounding_box(instance).size();
    ap.height = size.z();
    ap.name = obj->name;
    return ap;
}

